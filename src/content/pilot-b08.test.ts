const b08 = allUnits.find((u) => u.id === 'b08') as Unit;
const items = b08.lessons.flatMap((l) => l.exercises);
const practice = items.filter((e) => e.type !== 'learn');
const check = poolFiles['b08-check'].items as AssessmentItem[];
const S216 = ['b08-c01', 'b08-c02'];
const own = [...items, ...check.filter((i) => !S216.includes(i.id!))];
const byId = (id: string) => [...items, ...check].find((e) => e.id === id) as Exercise;
const pos = (id: string) => positionOf(byId(id));
const keysOf = (p: Position) => legalMoves(p).map(moveKey);
const moveOf = (p: Position, key: string) => {
  const m = legalMoves(p).find((x) => moveKey(x) === key);
  if (!m) throw new Error(`illegal ${key}`);
  return m;
};
const after = (p: Position, key: string) => makeMove(p, moveOf(p, key));
/** Material change for the mover after `key` and the best 4-ply line (opponent first), with that line. */
const line4 = (p: Position, key: string) => {
  const a = after(p, key);
  const r = search(a, { depth: 4, maxNodes: 3e6 });
  expect(r.complete, key).toBe(true);
  const reply = r.pv[0];
  return {
    v: -r.score - materialBalance(p.board, p.turn),
    reply,
    replyChecks: reply ? isInCheck(makeMove(a, reply)) : false,
    replyCaptures: reply ? reply.to === moveOf(p, key).to : false,
    replyTakes: reply ? a.board[reply.to] !== null : false,
  };
};
const guardOk = (id: string, p: Position, key: string) => {
  const v = syncSafety()(p, moveOf(p, key), { itemId: id });
  return v.status === 'checked' && v.safe;
};
const develops = (p: Position, key: string) => evaluatePredicate({ kind: 'development', increaseBy: 1 }, { before: p, moves: [moveOf(p, key)] }) === true;
const query = (id: string, q: SquareQuery) => querySquares(pos(id), q).map(squareName).sort();
const correct = (id: string) => (byId(id) as ChoiceExercise).options.filter((o) => o.correct).map((o) => o.id);
/** What the side NOT to move threatens: its material gain if it could move now (3 plies), and its first move. */
const threat = (p: Position) => {
  const opp = { ...p, turn: p.turn === 'red' ? 'black' : 'red' } as Position;
  const r = search(opp, { depth: 3, maxNodes: 3e6 });
  expect(r.complete).toBe(true);
  const first = r.pv[0];
  return { gain: r.score - materialBalance(opp.board, opp.turn), firstChecks: first ? isInCheck(makeMove(opp, first)) : false };
};

describe('unit b08 (S3.3.a)', () => {
  it('follows 02 b08: three lessons, learn cards first, ladders G2 G2 G1 G1 G0, the task b08-g1 last', () => {
    expect(b08.track).toBe('basics');
    expect(b08.lessons.map((l) => l.id)).toEqual(['b08l1', 'b08l2', 'b08l3']);
    const ladder = (lesson: number) => b08.lessons[lesson].exercises.filter((e) => e.type !== 'learn' && e.type !== 'play').map((e) => e.assist);
    for (const i of [0, 1, 2]) expect(ladder(i), String(i)).toEqual(['G2', 'G2', 'G1', 'G1', 'G0']);
    for (const lesson of b08.lessons) {
      const first = lesson.exercises.findIndex((e) => e.type !== 'learn');
      expect(first, lesson.id).toBeGreaterThan(0);
      expect(lesson.exercises.slice(first).every((e) => e.type !== 'learn'), lesson.id).toBe(true);
    }
    expect(b08.lessons[2].exercises.at(-1)!.id).toBe('b08-g1');
    expect(unitItems(b08).every(({ item }) => item.status === 'verified')).toBe(true);
    expect([...new Set(practice.map((e) => e.strand))].sort()).toEqual(['DE', 'PP', 'RS']);
    // New content (02 b08 "Reuses —"): authored, or generated by seeded self-play (seed recorded).
    expect(own.every((e) => e.source?.kind === 'authored' || (e.source?.kind === 'generated' && typeof e.source.seed === 'number'))).toBe(true);
    // Guided: threatened pieces after a shown move; independent: choices and decisions, mostly quiet positions.
    expect(b08.lessons[0].exercises.filter((e) => e.type === 'select-squares').every((e) => e.type === 'select-squares' && e.query?.kind === 'attacked-pieces')).toBe(true);
    expect(practice.filter((e) => e.nature === 'quiet').length * 4).toBeGreaterThanOrEqual(practice.length * 3);
  });

  it('both colours: 7 of 16 practice items as Black, including the task', () => {
    expect(practice.filter((e) => e.side === 'black').map((e) => e.id)).toEqual(['b08l1-03', 'b08l1-06', 'b08l2-04', 'b08l2-06', 'b08l3-04', 'b08l3-07', 'b08-g1']);
  });

  it('misconceptions b08.m1–m4 (the 02 list): each has a tagged learn card and a tagged wrong answer', () => {
    const ids = ['b08.m1', 'b08.m2', 'b08.m3', 'b08.m4'];
    expect([...new Set(items.filter((e) => e.type === 'learn').flatMap((e) => e.misconceptions ?? []))].sort()).toEqual(ids);
    const answers = own.flatMap((e) => (e.type === 'choice' ? e.options.filter((o) => !o.correct).map((o) => o.misconception) : e.type === 'decision' ? e.table.map((r) => r.misconception) : []));
    expect([...new Set(answers.filter((m): m is string => !!m && m.startsWith('b08')))].sort()).toEqual(ids);
    // Earlier misconceptions are reused only for "nothing is threatened" distractors (a defended piece "won").
    expect([...new Set(answers.filter((m): m is string => !!m && !m.startsWith('b08')))]).toEqual(['b07.m1']);
  });

  it('threatened pieces after a shown move: the legal facts', () => {
    expect(query('b08l1-03', { kind: 'attacked-pieces', side: 'black' })).toEqual(['b6', 'd9', 'g6']);
    expect(query('b08l1-04', { kind: 'attacked-pieces', side: 'red' })).toEqual(['b5', 'c2', 'e2']);
    expect(query('b08-c03', { kind: 'attacked-pieces', side: 'red' })).toEqual(['b4', 'f2']);
    expect(query('b08-c04', { kind: 'attacked-pieces', side: 'black' })).toEqual(['d7', 'e8', 'h5']);
  });

  it('"what does that move threaten?": a piece, a check that wins material, or nothing', () => {
    for (const id of ['b08l1-05', 'b08-c05']) expect(threat(pos(id)).gain, id).toBe(9);
    for (const id of ['b08l1-06', 'b08-c06']) {
      const t = threat(pos(id));
      expect(t.gain, id).toBe(9);
      expect(t.firstChecks, id).toBe(true);
      // Option b's premise is true (nothing is attacked yet); it is wrong because the threat is a check.
      expect(query(id, { kind: 'attacked-pieces', side: 'black' }), id).toEqual([]);
    }
    for (const id of ['b08l1-07', 'b08-c07']) expect(threat(pos(id)).gain, id).toBeLessThanOrEqual(0);
    for (const id of ['b08l1-05', 'b08l1-06', 'b08l1-07', 'b08-c05', 'b08-c06', 'b08-c07']) expect(correct(id), id).toEqual(['a']);
  }, 120_000);

  it('move choices: safe answers keep everything; m1 answers are captured, m3 answers walk into a check, m4 answers improve nothing', () => {
    const choices = own.filter((e): e is ChoiceExercise => e.type === 'choice' && e.options.some((o) => o.move));
    expect(choices.map((e) => e.id)).toEqual(['b08l2-03', 'b08l2-04', 'b08l2-05', 'b08l2-06', 'b08l3-05', 'b08-c08', 'b08-c09', 'b08-c10', 'b08-c15']);
    for (const c of choices) {
      const p = positionOf(c);
      for (const o of c.options) {
        const l = line4(p, o.move!);
        const tag = `${c.id} ${o.id}`;
        if (o.correct) {
          expect(guardOk(c.id!, p, o.move!), tag).toBe(true);
          expect(l.v, tag).toBeGreaterThanOrEqual(0);
          if (c.id === 'b08l3-05' || c.id === 'b08-c15') expect(develops(p, o.move!), tag).toBe(true);
        } else if (o.misconception === 'b08.m1') {
          expect(guardOk(c.id!, p, o.move!), tag).toBe(false);
          expect(l.v, tag).toBeLessThan(0);
          expect(l.replyCaptures, tag).toBe(true);
        } else if (o.misconception === 'b08.m3') {
          expect(l.v, tag).toBeLessThanOrEqual(-2);
          expect(l.replyChecks, tag).toBe(true);
        } else {
          expect(o.misconception, tag).toBe('b08.m4');
          expect(guardOk(c.id!, p, o.move!), tag).toBe(true);
          expect(l.v, tag).toBeGreaterThanOrEqual(0);
          expect(develops(p, o.move!), tag).toBe(false);
        }
      }
    }
  }, 300_000);

  it('decisions: accepted moves pass the guard and keep the material at depth 4 (and develop, in b08l3); refused authored rows lose; no move wins ≥ 2', () => {
    const decisions = own.filter((e): e is DecisionExercise => e.type === 'decision');
    expect(decisions.map((e) => e.id)).toEqual(['b08l2-07', 'b08l3-03', 'b08l3-04', 'b08l3-06', 'b08l3-07', 'b08-c11', 'b08-c12', 'b08-c13', 'b08-c14', 'b08-c16']);
    for (const d of decisions) {
      const p = positionOf(d);
      expect(d.table.map((r) => r.move).sort(), d.id).toEqual(keysOf(p).sort());
      // b08l3 and its pool items ask for a safe move that develops a piece (pool items keep the lesson id as `objective`).
      const improving = ['b08l3-03', 'b08l3-04', 'b08l3-06', 'b08l3-07', 'b08-c13', 'b08-c14', 'b08-c16'].includes(d.id!);
      for (const row of d.table) {
        const tag = `${d.id} ${row.move}`;
        const m = moveOf(p, row.move);
        expect(moveScore(p, m, 2) - materialBalance(p.board, p.turn), tag).toBeLessThan(2);
        if (isAccepted(row.class)) {
          expect(guardOk(d.id!, p, row.move), tag).toBe(true);
          expect(line4(p, row.move).v, tag).toBeGreaterThanOrEqual(0);
          if (improving) expect(develops(p, row.move), tag).toBe(true);
        } else if (row.source === 'authored') {
          const l = line4(p, row.move);
          if (row.class === 'error') expect(l.v, tag).toBeLessThan(0);
          else expect(l.v, tag).toBeGreaterThanOrEqual(0);
        } else if (row.class === 'error') expect(guardOk(d.id!, p, row.move), tag).toBe(false);
      }
      const t = d.table.find((r) => r.move === d.feedback!.temptingAlternative.move)!;
      expect(isAccepted(t.class), d.id).toBe(false);
      const l = line4(p, t.move);
      expect(l.v, d.id).toBeLessThan(0);
      if (t.misconception === 'b08.m3') expect(l.replyChecks, d.id).toBe(true);
      else {
        // b08.m1 (only my plan matters): the reply simply takes something the move left undefended.
        expect(t.misconception, d.id).toBe('b08.m1');
        expect(l.replyTakes, d.id).toBe(true);
      }
    }
  }, 600_000);

  it('b08-g1: short drill as Black from a simplified self-play position vs safe-sparring(2), R1 70 + R0 30', () => {
    const g = byId('b08-g1') as PlayExercise;
    expect(g).toMatchObject({ type: 'play', task: 'drill', side: 'black', cap: 11, rubrics: [{ rubric: 'R1', weight: 70 }, { rubric: 'R0', weight: 30 }] });
    expect(g.cap).toBeGreaterThanOrEqual(6);
    expect(g.cap).toBeLessThanOrEqual(12);
    expect(g.tree).toBeUndefined();
    expect(g.source).toMatchObject({ kind: 'generated', seed: 22180 });
    const p = positionOf(g);
    expect(p.turn).toBe('black');
    expect(isInCheck(p)).toBe(false);
    expect(Math.abs(materialBalance(p.board, p.turn))).toBeLessThanOrEqual(1);
  });
});

/** Learner-relative signature of a check item: kind of task + material (own / opponent piece types). */
function signature(e: AssessmentItem): string {
  const p = positionOf(e);
  const mine = p.turn;
  const types = (m: boolean) => p.board.filter((x) => x && (x.color === mine) === m).map((x) => x!.type).sort().join(',');
  const task = e.type === 'move' ? `move:${e.goal.kind}` : e.type === 'select-squares' ? `select:${JSON.stringify(e.query ?? e.region ?? 'square')}` : e.type;
  return `${task} | ${types(true)} | ${types(false)}`;
}

describe('b08 check pool (03 §4.1–§4.3)', () => {
  it('16 items: 5 / 5 / 6 per lesson objective, all G0, 8 as Black, 5 safety-critical, the S2.16 items kept', () => {
    expect(check).toHaveLength(16);
    expect(check.map((i) => i.id)).toEqual(Array.from({ length: 16 }, (_, i) => `b08-c${String(i + 1).padStart(2, '0')}`));
    expect(poolFiles['b08-check']).toMatchObject({ id: 'b08-check', kind: 'check', unit: 'b08', primaryStrand: 'RS' });
    expect(['b08l1', 'b08l2', 'b08l3'].map((l) => check.filter((i) => i.objective === l).length)).toEqual([5, 5, 6]);
    expect(check.every((i) => i.unit === 'b08' && i.assist === 'G0')).toBe(true);
    expect(check.filter((i) => S216.includes(i.id!)).every((i) => i.status === 'reviewed' && i.critical)).toBe(true);
    expect(check.filter((i) => !S216.includes(i.id!)).every((i) => i.status === 'verified')).toBe(true);
    expect(check.filter((i) => i.critical).map((i) => i.id)).toEqual(['b08-c01', 'b08-c02', 'b08-c08', 'b08-c09', 'b08-c10']);
    expect(check.filter((i) => i.side === 'black')).toHaveLength(8);
    for (const i of check as (AssessmentItem & { hints?: unknown; highlight?: unknown; from?: unknown })[]) {
      expect(i.hints, i.id).toBeUndefined();
      expect(i.highlight, i.id).toBeUndefined();
      expect(i.from, i.id).toBeUndefined();
    }
  });

  it('unseen (03 §4.2 rule 4): no check item is near any lesson item of any unit, nor another b08 check item', () => {
    const others = [
      ...allUnits.flatMap((u) => u.lessons.flatMap((l) => l.exercises.map((e, i) => ({ ref: e.id ?? `${l.id}#${i}`, pos: positionOf(e) })))),
      ...check.map((e) => ({ ref: e.id!, pos: positionOf(e) })),
    ];
    const hits = check.flatMap((c) => others.filter((o) => o.ref !== c.id && nearDuplicate(positionOf(c), o.pos)).map((o) => `${c.id} ~ ${o.ref}`));
    expect(hits).toEqual([]);
  });

  // The pattern-mirror rule is about composed positions; the self-play decision positions (full boards, > 20 pieces,
  // including the S2.16 items) all carry nearly the same material, so they are kept apart by the near-duplicate test only.
  it('no two composed check items share a task and the same learner-relative material (pattern mirrors)', () => {
    const seen = new Map<string, string>();
    const clashes: string[] = [];
    const composed = check.filter((e) => positionOf(e).board.filter(Boolean).length <= 20);
    expect(composed.map((e) => e.id)).toEqual(['b08-c03', 'b08-c04', 'b08-c05', 'b08-c06', 'b08-c07', 'b08-c08', 'b08-c09', 'b08-c10']);
    for (const e of composed) {
      const sig = signature(e);
      if (seen.has(sig)) clashes.push(`${seen.get(sig)} ~ ${e.id}: ${sig}`);
      else seen.set(sig, e.id!);
    }
    expect(clashes).toEqual([]);
  });

  it('builds three 8-item forms with 2 interleaved b01–b07 items each (≥ 3 Black, every objective, a critical item, ≤ half exposed)', () => {
    const earlier = ['b01-check', 'b02-check', 'b03-check', 'b04-check', 'b05-check', 'b06-check', 'b07-check'].flatMap((p) => poolFiles[p].items as AssessmentItem[]);
    const base = { unit: 'b08', objectives: b08.lessons.map((l) => l.id), primaryStrand: 'RS' as const, poolId: 'b08-check', assessmentVersion: 1, own: check, earlier };
    const exposed = new Set<string>();
    for (const [attempt, maxExposed] of [[1, 0], [2, 0], [3, 4]] as const) {
      const r = assembleCheckForm({ ...base, exposed, seed: attempt });
      expect(r.ok, `attempt ${attempt}`).toBe(true);
      if (!r.ok) continue;
      expect(r.form.items).toHaveLength(8);
      expect(r.form.items.filter((i) => i.unit === 'b08')).toHaveLength(6);
      expect(new Set(r.form.items.filter((i) => i.unit === 'b08').map((i) => i.objective)).size).toBe(3);
      expect(r.form.items.filter((i) => i.side === 'black').length).toBeGreaterThanOrEqual(3);
      expect(r.form.items.some((i) => i.critical)).toBe(true);
      expect(r.form.exposedCount).toBeLessThanOrEqual(maxExposed);
      for (const i of r.form.items) exposed.add(i.id!);
    }
  });
});
