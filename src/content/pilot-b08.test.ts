// Content checks of unit b08 "The pre-move safety routine" (S3.3.a: lessons b08l1–b08l3, practical task b08-g1, check
// pool b08-check extended from the two S2.16 items), loaded in release state REL-P (`verified` until the content review).
// The validator and the pool validator run on it with everything else. This file pins what the unit must show (02 b08,
// 03 §4.1–§4.3, §5) and that every claim holds for EVERY accepted move (b05–b07 review lessons): "safe" = the Basic
// guard passes AND the best line of 4 plies wins nothing; refused moves lose at depth 4.
import { describe, expect, it } from 'vitest';
import { isInCheck, legalMoves, makeMove, materialBalance, moveScore, squareName, type Position } from '../engine';
import { search } from '../analysis';
import { evaluatePredicate } from '../analysis/judge';
import { assembleCheckForm } from '../assessment/checks';
import { positionOf, querySquares } from '../lessons/answers';
import { isAccepted, moveKey } from '../lessons/decision';
